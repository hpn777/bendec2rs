use serde_json::json;

#[test]
fn uppercase_ordinals_are_consumed_before_acronym_boundaries() {
    // Pinned Lodash word grammar: ordinal alternatives consume both suffix
    // characters and end the word even before a following lowercase letter.
    for (name, expected) in [
        ("a1STb", "a_1st_b"),
        ("2NDaValue", "2nd_a_value"),
        ("2NDabValue", "2nd_ab_value"),
        ("4THaValue", "4th_a_value"),
        ("4THabValue", "4th_ab_value"),
        ("11thValue", "11_th_value"),
        ("1sTValue", "1_s_t_value"),
    ] {
        let output = bendec2rs::generate_string(
            &[json!({"name": "Names", "fields": [{"name": name, "type": "u8"}]})],
            &json!({}),
        )
        .unwrap();
        assert!(
            output.contains(&format!("  pub {expected}: u8,")),
            "{name}: {output}"
        );
    }
}

#[test]
fn inherited_default_type_mappings_match_javascript_object_prototype() {
    let header = "/** GENERATED BY BENDEC TYPE GENERATOR */\n#[allow(unused_imports)]\nuse serde::{Deserialize, Deserializer, Serialize, Serializer};";
    for (name, expected) in [
        ("constructor", "[object Object]"),
        ("toString", "[object Object]"),
        ("valueOf", "[object Object]"),
        ("hasOwnProperty", "false"),
        ("prototype", "u8"),
    ] {
        // Mapped aliases bypass descriptions and newtype metadata upstream.
        let output =
            bendec2rs::generate_string(&[json!({"name": name, "alias": "u8"})], &json!({}))
                .unwrap();
        assert_eq!(output, format!("{header}\npub type {name} = {expected};"));
    }
    assert_eq!(
        bendec2rs::generate_string(&[json!({"name": "__proto__", "alias": "u8"})], &json!({}))
            .unwrap_err(),
        "typeMap[typeName] is not a function"
    );
}

#[test]
fn explicit_mapping_overrides_inherited_defaults_and_metadata() {
    for name in [
        "constructor",
        "toString",
        "valueOf",
        "hasOwnProperty",
        "__proto__",
    ] {
        let output = bendec2rs::generate_string(
            &[json!({"name": name, "alias": "u8", "description": "ignored"})],
            &json!({
                "typeMapping": {name: "u64"},
                "meta": {name: {"newtype": {"kind": "Public"}, "annotations": ["ignored"]}}
            }),
        )
        .unwrap();
        assert!(output.ends_with(&format!("pub type {name} = u64;")));
        assert!(!output.contains("ignored"));
    }
}

#[test]
fn prototype_metadata_does_not_override_default_mapping_precedence() {
    for name in ["constructor", "toString", "valueOf", "hasOwnProperty"] {
        let definitions = [json!({"name": name, "alias": "u8", "description": "ignored"})];
        let plain = bendec2rs::generate_string(&definitions, &json!({})).unwrap();
        let with_metadata = bendec2rs::generate_string(
            &definitions,
            &json!({"meta": {name: {"newtype": {"kind": "Public"}, "annotations": ["ignored"]}}}),
        )
        .unwrap();
        assert_eq!(with_metadata, plain);
    }
    for options in [
        json!({}),
        json!({"meta": {"__proto__": {"annotations": []}}}),
    ] {
        assert_eq!(
            bendec2rs::generate_string(&[json!({"name": "__proto__", "alias": "u8"})], &options,)
                .unwrap_err(),
            "typeMap[typeName] is not a function"
        );
    }
    assert_eq!(
        bendec2rs::generate_string(
            &[json!({"name": "Fields", "fields": [{"name": "x", "type": "__proto__"}]})],
            &json!({}),
        )
        .unwrap_err(),
        "typeMap[key] is not a function"
    );
}
